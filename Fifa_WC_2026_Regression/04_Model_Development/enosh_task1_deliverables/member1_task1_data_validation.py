#!/usr/bin/env python3
"""Member 1 / Task 1 — FIFA World Cup 2026 dataset validation and statistics.

Academic integrity: AI assistance was used to draft this code and its validation
logic. All statistics and reported findings are generated by pandas/numpy from
the user's supplied 'Master_104_Matches' worksheet; no web data is used.
The input workbook is read-only: no original cells are modified or saved.

Requirements: Python 3.9+, pandas, numpy, openpyxl.
Example:
  python member1_task1_data_validation.py \
      --input "FIFA_WC2026_All_8_Variables_Master_Consistent_Formatting.xlsx" \
      --output-dir .

Outputs in output-dir:
  member1_task1_descriptive_statistics.csv
  member1_task1_validation_report.md
"""

from __future__ import annotations

import argparse
import hashlib
import math
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

SHEET = "Master_104_Matches"
EXPECTED_START = pd.Timestamp("2026-06-11")
EXPECTED_END = pd.Timestamp("2026-07-19")
EXPECTED_IDS = set(range(1, 105))

FEATURE_NAMES = [
    "fifa_rank_diff",
    "elo_rating_diff",
    "last5_avg_goals_scored_diff",
    "last5_avg_goals_conceded_diff",
    "last5_win_rate_diff",
    "last5_clean_sheet_rate_diff",
    "rest_days_diff",
    "last5_opponent_strength_diff",
]
TARGET_NAME = "goal_difference"
MODEL_COLUMNS = FEATURE_NAMES + [TARGET_NAME]
REQUIRED_COLUMNS = [
    "match_id", "match_date", "stage", "group", "team_a", "team_b",
    *MODEL_COLUMNS, "team_a_goals", "team_b_goals",
]


def sha256(path: Path) -> str:
    """Fingerprint the input before/after reading, without editing it."""
    h = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def md_cell(value: Any) -> str:
    """Escape values so diagnostic rows render reliably as Markdown."""
    if value is None or (not isinstance(value, (list, dict)) and pd.isna(value)):
        return "(blank)"
    if isinstance(value, (float, np.floating)):
        return f"{float(value):.6g}"
    return str(value).replace("|", "\\|").replace("\n", " ")


def make_markdown_table(headers: list[str], rows: list[list[Any]]) -> str:
    parts = ["| " + " | ".join(headers) + " |", "| " + " | ".join(["---"] * len(headers)) + " |"]
    parts.extend("| " + " | ".join(md_cell(x) for x in row) + " |" for row in rows)
    return "\n".join(parts)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input", required=True, type=Path,
        help="Path to original input Excel workbook (relative or absolute).",
    )
    parser.add_argument(
        "--output-dir", type=Path, default=Path("."),
        help="Directory for generated CSV and Markdown report (default: current directory).",
    )
    args = parser.parse_args()
    input_path = args.input.expanduser().resolve(strict=True)
    output_dir = args.output_dir.expanduser().resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    input_hash_before = sha256(input_path)
    # Read the designated sheet only. The other sheets are not modelling rows.
    df = pd.read_excel(input_path, sheet_name=SHEET, engine="openpyxl")
    missing_cols = [col for col in REQUIRED_COLUMNS if col not in df.columns]
    if missing_cols:
        raise ValueError(f"Missing required columns: {missing_cols}")

    issues: list[dict[str, Any]] = []
    checks: list[tuple[str, str, str]] = []

    def issue(row_index: int | None, column: str, observed: Any,
              explanation: str, severity: str = "ERROR") -> None:
        match_id = "N/A" if row_index is None else md_cell(df.iloc[row_index]["match_id"])
        issues.append({"match_id": match_id, "column": column,
                       "observed": observed, "severity": severity,
                       "explanation": explanation})

    def check(label: str, passed: bool, detail: str) -> None:
        checks.append((label, "PASS" if passed else "REVIEW", detail))

    # 1: number of match rows; do not drop rows for any failed check.
    check("1. Exactly 104 match records", len(df) == 104,
          f"Read {len(df)} rows from {SHEET}.")
    if len(df) != 104:
        issue(None, "match_id", len(df), "Record count differs from 104.")

    # 2: complete, integer, unique match_id sequence 1..104.
    raw_ids = df["match_id"]
    parsed_ids = pd.to_numeric(raw_ids, errors="coerce")
    valid_id_values = parsed_ids.notna() & np.isfinite(parsed_ids) & (parsed_ids % 1 == 0)
    invalid_id_indices = [i for i in range(len(df)) if not bool(valid_id_values.iloc[i])]
    for i in invalid_id_indices:
        issue(i, "match_id", raw_ids.iloc[i], "Missing/non-integer/invalid match ID.")
    usable_ids = parsed_ids.loc[valid_id_values].astype("int64")
    duplicate_indices = set(usable_ids.index[usable_ids.duplicated(keep=False)].tolist())
    for i in sorted(duplicate_indices):
        issue(int(i), "match_id", raw_ids.loc[i], "Duplicate match ID.")
    ids_set = set(usable_ids.tolist())
    missing_ids = sorted(EXPECTED_IDS - ids_set)
    unexpected_ids = sorted(ids_set - EXPECTED_IDS)
    check("2. Unique complete match IDs 1–104",
          len(invalid_id_indices) == 0 and len(duplicate_indices) == 0
          and not missing_ids and not unexpected_ids,
          f"Invalid IDs: {len(invalid_id_indices)}; duplicate rows with IDs: {len(duplicate_indices)}; "
          f"missing IDs: {missing_ids or 'none'}; unexpected IDs: {unexpected_ids or 'none'}.")
    if missing_ids:
        issue(None, "match_id", missing_ids, "Missing expected IDs.")
    if unexpected_ids:
        issue(None, "match_id", unexpected_ids, "Unexpected IDs outside 1..104.")

    # 3 and 4: missing modelling values, numeric typing and finite numbers.
    numeric: dict[str, pd.Series] = {}
    missing_counts: dict[str, int] = {}
    invalid_counts: dict[str, int] = {}
    for col in MODEL_COLUMNS + ["team_a_goals", "team_b_goals"]:
        raw = df[col]
        values = pd.to_numeric(raw, errors="coerce")
        numeric[col] = values
        raw_missing = raw.isna()
        missing_counts[col] = int(raw_missing.sum())
        nonnumeric = raw.notna() & values.isna()
        bool_mask = raw.map(lambda x: isinstance(x, (bool, np.bool_)))
        nonfinite = values.notna() & ~np.isfinite(values)
        invalid_mask = nonnumeric | bool_mask | nonfinite
        invalid_counts[col] = int(invalid_mask.sum())
        for i in np.flatnonzero(raw_missing.to_numpy()):
            if col in MODEL_COLUMNS:
                issue(int(i), col, raw.iloc[i], "Missing modelling value.")
        for i in np.flatnonzero(invalid_mask.to_numpy()):
            issue(int(i), col, raw.iloc[i], "Expected a finite numeric value (boolean/text/infinity is invalid).")
        if col in MODEL_COLUMNS and not pd.api.types.is_numeric_dtype(raw.dtype):
            # Numeric-looking text is still a data-type quality issue.
            for i in np.flatnonzero((raw.notna() & ~invalid_mask).to_numpy()):
                if isinstance(raw.iloc[int(i)], str):
                    issue(int(i), col, raw.iloc[int(i)], "Numeric value stored as text.", "REVIEW")

    check("3. No missing target or explanatory values",
          all(missing_counts[c] == 0 for c in MODEL_COLUMNS),
          "; ".join(f"{c}: {missing_counts[c]}" for c in MODEL_COLUMNS))
    check("4. All nine modelling columns are finite numeric data",
          all(invalid_counts[c] == 0 for c in MODEL_COLUMNS)
          and all(pd.api.types.is_numeric_dtype(df[c].dtype) for c in MODEL_COLUMNS),
          "Invalid nonnumeric/boolean/infinite values: "
          + (", ".join(f"{c}={invalid_counts[c]}" for c in MODEL_COLUMNS if invalid_counts[c]) or "none")
          + ". All modelling columns should also have numeric storage types.")

    # 5: target matches score arithmetic using exact integers where possible.
    a = numeric["team_a_goals"]
    b = numeric["team_b_goals"]
    y = numeric[TARGET_NAME]
    valid_scores = a.notna() & b.notna() & y.notna() & np.isfinite(a) & np.isfinite(b) & np.isfinite(y)
    equal = pd.Series(False, index=df.index)
    equal.loc[valid_scores] = np.isclose(
        (a - b).loc[valid_scores].to_numpy(dtype=float),
        y.loc[valid_scores].to_numpy(dtype=float), atol=1e-9, rtol=0,
    )
    score_errors = list(np.flatnonzero((valid_scores & ~equal).to_numpy()))
    for i in score_errors:
        issue(int(i), TARGET_NAME, y.iloc[i],
              f"Does not equal team_a_goals ({md_cell(a.iloc[i])}) "
              f"minus team_b_goals ({md_cell(b.iloc[i])}).")
    check("5. Goal differences agree with the score columns",
          bool(valid_scores.all() and not score_errors),
          f"Correct calculations: {int((valid_scores & equal).sum())}/{len(df)}; mismatches: {len(score_errors)}.")

    # 6: completely repeated rows, including all 20 imported columns.
    repeated_rows = df.duplicated(keep=False)
    for i in np.flatnonzero(repeated_rows.to_numpy()):
        issue(int(i), "(complete row)", df.iloc[i]["match_id"], "Full-row duplicate record.")
    check("6. No duplicate complete rows", not bool(repeated_rows.any()),
          f"Rows involved in full-row duplication: {int(repeated_rows.sum())}.")

    # 7: date validity and tournament range. Calendar dates are compared locally;
    # do not use publication dates or web records at this stage.
    date_raw = df["match_date"]
    dates = pd.to_datetime(date_raw, errors="coerce")
    bad_dates = dates.isna() | dates.lt(EXPECTED_START) | dates.gt(EXPECTED_END)
    for i in np.flatnonzero(bad_dates.to_numpy()):
        issue(int(i), "match_date", date_raw.iloc[i],
              "Unreadable date or outside 2026-06-11 through 2026-07-19.")
    check("7. Readable match dates inside tournament period", not bool(bad_dates.any()),
          f"Unreadable/out-of-range dates: {int(bad_dates.sum())}; "
          f"earliest: {md_cell(dates.min())}; latest: {md_cell(dates.max())}.")

    # 8: win and clean-sheet differences are differences of rates in [0,1].
    rate_problem_count = 0
    for col in ("last5_win_rate_diff", "last5_clean_sheet_rate_diff"):
        s = numeric[col]
        outside = s.notna() & ((s < -1 - 1e-9) | (s > 1 + 1e-9))
        rate_problem_count += int(outside.sum())
        for i in np.flatnonzero(outside.to_numpy()):
            issue(int(i), col, s.iloc[i], "Difference of two rates must lie in [-1, 1].")
    check("8. X5/X6 lie between −1 and +1", rate_problem_count == 0,
          f"Out-of-range values: {rate_problem_count}.")

    # 9: sign and zero counts. They are expected for Team A minus Team B;
    # do not flag negative or zero values as data-integrity failures.
    sign_rows = []
    for col in MODEL_COLUMNS:
        s = numeric[col]
        sign_rows.append([col, int((s < 0).sum()), int((s == 0).sum()), int((s > 0).sum())])
    check("9. Negative and zero values handled without coercion", True,
          "Negative and zero observations are retained; counts are reported separately below.")

    # 10: robust IQR screening for *review*, not automatic deletion.
    outlier_rows: list[list[Any]] = []
    for col in MODEL_COLUMNS:
        s = numeric[col].where(np.isfinite(numeric[col]))
        nonnull = s.dropna()
        if len(nonnull) < 4:
            continue
        q1, q3 = nonnull.quantile([0.25, 0.75])
        iqr = q3 - q1
        if iqr == 0:
            # Avoid labelling every non-median value an outlier when IQR=0.
            continue
        lower = q1 - 1.5 * iqr
        upper = q3 + 1.5 * iqr
        flag = s.notna() & ((s < lower) | (s > upper))
        for i in np.flatnonzero(flag.to_numpy()):
            val = s.iloc[i]
            direction = "below" if val < lower else "above"
            explanation = (f"Outside 1.5×IQR review band [{lower:.4f}, {upper:.4f}]; "
                           f"value is {direction} the bound. Not automatically an error.")
            issue(int(i), col, val, explanation, "REVIEW")
            outlier_rows.append([df.iloc[int(i)]["match_id"], col, val,
                                 f"{lower:.4f}", f"{upper:.4f}"])
    check("10. Unusual values identified without removal", True,
          f"Flagged {len(outlier_rows)} column-specific observations using 1.5×IQR; all retained.")

    # Additional structural check: absent group labels in knockout rows are expected.
    missing_group = int(df["group"].isna().sum())
    group_stage = df["stage"].eq("Group Stage")
    group_missing_in_group = int((group_stage & df["group"].isna()).sum())
    group_present_in_knockout = int((~group_stage & df["group"].notna()).sum())
    same_team = df["team_a"].astype(str).str.strip().eq(df["team_b"].astype(str).str.strip())
    for i in np.flatnonzero(same_team.to_numpy()):
        issue(int(i), "team_a/team_b", df.iloc[i]["team_a"], "Team A and Team B are identical.")
    for i in np.flatnonzero((group_stage & df["group"].isna()).to_numpy()):
        issue(int(i), "group", None, "Group-stage fixture missing its group label.")
    for i in np.flatnonzero((~group_stage & df["group"].notna()).to_numpy()):
        issue(int(i), "group", df.iloc[i]["group"], "Knockout fixture unexpectedly has a group label.", "REVIEW")

    # Descriptive statistics. Use pandas sample SD (ddof=1) and linear percentiles.
    stats_rows: list[dict[str, Any]] = []
    for col in MODEL_COLUMNS:
        s = numeric[col].replace([np.inf, -np.inf], np.nan)
        valid = s.dropna()
        stats_rows.append({
            "variable": col,
            "valid_observations": int(valid.count()),
            "mean": float(valid.mean()) if len(valid) else math.nan,
            "median": float(valid.median()) if len(valid) else math.nan,
            "std_dev": float(valid.std(ddof=1)) if len(valid) > 1 else math.nan,
            "minimum": float(valid.min()) if len(valid) else math.nan,
            "maximum": float(valid.max()) if len(valid) else math.nan,
            "q1_25th_percentile": float(valid.quantile(0.25)) if len(valid) else math.nan,
            "q3_75th_percentile": float(valid.quantile(0.75)) if len(valid) else math.nan,
            "missing_values": int(df[col].isna().sum()),
        })
    stats = pd.DataFrame(stats_rows)
    csv_path = output_dir / "member1_task1_descriptive_statistics.csv"
    stats.to_csv(csv_path, index=False, float_format="%.6f")

    positive = int((y > 0).sum())
    negative = int((y < 0).sum())
    zero = int((y == 0).sum())
    invalid_y = int(y.isna().sum())

    stats_md_rows = []
    for r in stats_rows:
        def fmt(value: Any) -> str:
            return f"{value:.3f}" if isinstance(value, (float, np.floating)) else str(value)
        stats_md_rows.append([
            r["variable"], r["valid_observations"], fmt(r["mean"]),
            fmt(r["median"]), fmt(r["std_dev"]), fmt(r["minimum"]),
            fmt(r["maximum"]), fmt(r["q1_25th_percentile"]),
            fmt(r["q3_75th_percentile"]), r["missing_values"],
        ])

    issue_md = make_markdown_table(
        ["Match ID", "Column", "Observed value", "Level", "Explanation"],
        [[r["match_id"], r["column"], r["observed"], r["severity"], r["explanation"]]
         for r in issues],
    ) if issues else "No errors or unusual observations were detected."

    # Avoid invented claims about cross-variable relationships and external accuracy.
    max_abs_rest_idx = numeric["rest_days_diff"].abs().idxmax()
    max_abs_rest_id = df.loc[max_abs_rest_idx, "match_id"]
    max_abs_rest = numeric["rest_days_diff"].loc[max_abs_rest_idx]
    stage_table = make_markdown_table(
        ["Tournament stage", "Matches"],
        [[stage, int(cnt)] for stage, cnt in df["stage"].value_counts().items()]
    )
    check_table = make_markdown_table(
        ["Integrity test", "Outcome", "Details"], [list(row) for row in checks]
    )
    stats_table = make_markdown_table(
        ["Variable", "Valid", "Mean", "Median", "SD", "Min", "Max", "Q1", "Q3", "Missing"],
        stats_md_rows,
    )
    sign_table = make_markdown_table(
        ["Variable", "Negative", "Zero", "Positive"], sign_rows,
    )
    num_errors = sum(r["severity"] == "ERROR" for r in issues)
    num_review = sum(r["severity"] == "REVIEW" for r in issues)
    report = f"""# Member 1 — Task 1: Dataset integrity and descriptive statistics

## Scope and provenance

- **Source:** `{input_path.name}` (original workbook read-only).
- **Worksheet:** `{SHEET}`; supporting sheets were not used as modelling observations.
- **Observed shape:** {len(df)} rows × {len(df.columns)} columns.
- **Source workbook SHA-256:** `{input_hash_before}`.
- **Model:** eight explanatory variables (`X1`–`X8`) and `goal_difference` as target.
- **Processing:** pandas/numpy under Python 3; no historical-data lookups, feature scaling, predictive modelling, correlation analysis, transformations, value replacement, filtering, or row deletion.

### Stage counts

{stage_table}

The workbook has {missing_group} missing `group` labels. Of these, {int((~group_stage & df['group'].isna()).sum())} are in knockout matches, where a group label is not expected. There are {group_missing_in_group} group-stage records with a missing group and {group_present_in_knockout} knockout records with a filled group. The `result_note` column contains {int(df['result_note'].isna().sum())} blanks; it is not a predictor.

## Integrity-validation methodology and outcomes

{check_table}

- IDs must be exactly 1 to 104, unique and integer-valued. Numerical data are checked for missing values, invalid text, booleans, and non-finite values.
- Match dates must parse correctly and fall between 11 June and 19 July 2026, inclusive. This checks date representation and range **within the supplied file**, not external FIFA factual accuracy.
- Goal differences are compared against `team_a_goals - team_b_goals` with a numeric tolerance of 1e-9.
- Duplicate complete rows are checked across all imported columns.
- X5 and X6 are differences of two proportions, so values outside [-1, 1] are impossible.
- Negative and zero differences are valid because signs depend on the ordered Team A/Team B subtraction. The script retains them unchanged.
- An outlier-screening flag is raised for values below Q1 − 1.5×IQR or above Q3 + 1.5×IQR. This is **screening for review only**, not evidence of incorrect data.

## Descriptive statistics

{stats_table}

**Definitions:** SD is the sample standard deviation (`ddof=1`). Q1 and Q3 are the 25th and 75th percentiles from pandas' default linear interpolation. The downloadable CSV keeps six decimal places; the report table displays three. Statistics use all valid original observations and make no train/test split.

## Goal-difference distribution

| Outcome in recorded goals | Matches | Percentage |
| --- | ---: | ---: |
| Positive (`goal_difference > 0`) — Team A scored more goals | {positive} | {(positive/len(df)*100):.2f}% |
| Negative (`goal_difference < 0`) — Team B scored more goals | {negative} | {(negative/len(df)*100):.2f}% |
| Zero (`goal_difference = 0`) — Teams had equal goal totals | {zero} | {(zero/len(df)*100):.2f}% |
| Missing/invalid target values | {invalid_y} | {(invalid_y/len(df)*100):.2f}% |

A zero goal difference indicates level goals, **not necessarily that a knockout match finished undecided after a penalty shootout**. Penalty shootout goals are not part of the recorded target calculation.

### Negative and zero-value checks (all preserved)

{sign_table}

## Observations requiring attention

- **Validation errors:** {num_errors}. **Review-only observations:** {num_review}. (A single match may be flagged in several feature columns.)
- **IQR flags:** {len(outlier_rows)} feature-specific observations; these remain in the dataset without any correction.
- **Largest absolute X7 value:** Match {max_abs_rest_id}, `rest_days_diff = {md_cell(max_abs_rest)}`. This value is unusually distant from the typical X7 interval and merits inspection of its previous-match dates; it is *not* automatically an error.

{issue_md}

## Important descriptive findings (based on calculated numbers)

- The mean recorded goal difference is **{stats_rows[-1]['mean']:.3f}**, while the median is **{stats_rows[-1]['median']:.3f}**. The observed target ranges from **{stats_rows[-1]['minimum']:.0f}** to **+{stats_rows[-1]['maximum']:.0f}** goals.
- The target has **{positive} positive**, **{negative} negative**, and **{zero} zero** differences; these are match outcome categories, not modelling performance measures.
- X7 (`rest_days_diff`) has median **{stats_rows[6]['median']:.0f}**, and **{int((numeric['rest_days_diff'] == 0).sum())}/{len(df)}** matches ({100 * int((numeric['rest_days_diff'] == 0).sum()) / len(df):.2f}%) have equal calendar rest intervals. Its range **{stats_rows[6]['minimum']:.0f}** to **+{stats_rows[6]['maximum']:.0f}** highlights a potentially influential extreme observation.
- `elo_rating_diff` has a standard deviation of **{stats_rows[1]['std_dev']:.3f} Elo points**, compared with **{stats_rows[4]['std_dev']:.3f}** for the dimensionless `last5_win_rate_diff`. These are different units, so raw scale alone does not establish predictive importance.
- The IQR method marks **{len(outlier_rows)} feature-level observations** for review. They have not been deleted, clipped, or reclassified as data errors.

## Implications for future EDA and regression

1. The supplied master worksheet has {len(df)} rows. Its modelling variables can be described without dropping or imputing any observation. If future corrections are justified, record them transparently before modelling.
2. Team A minus Team B is the required direction for all eight features and the target. A negative value conveys direction, not an invalid measurement.
3. `{TARGET_NAME}` is calculated from outcome goals, and `team_a_goals`, `team_b_goals`, and `result_note` must **not** enter the predictor matrix. They may be used solely for integrity checks or explanatory reporting.
4. The large X7 observation and other IQR flags should be investigated before model training. No outliers were removed, winsorised, or rescaled in this task. Their effect on the eventual model has not been tested.
5. Feature magnitudes differ substantially (for example Elo differences and rate differences), but no scaling has been done. Any preprocessing parameters in later stages must be learned from training data only to avoid leakage.
6. This task did **not** estimate correlations, fit regression coefficients, select variables, split train/test sets, or measure predictive performance. Completeness and arithmetic consistency alone cannot establish that all externally collected historical figures are accurate.

## Academic-integrity note

Generative AI assisted in drafting the Python script, validation checks, explanatory text, and report generation. Numerical results, counts, and flags are computed directly from the supplied worksheet by pandas and numpy. The work does **not** conduct external historical research, certify external source quality, or claim that reproducible calculations establish factual correctness of every upstream explanatory variable.
"""

    report_path = output_dir / "member1_task1_validation_report.md"
    report_path.write_text(report, encoding="utf-8")
    input_hash_after = sha256(input_path)
    if input_hash_before != input_hash_after:
        raise RuntimeError("Input file hash changed during validation; check file access!")

    print(f"Input workbook: {input_path.name}")
    print(f"Sheet: {SHEET}; rows: {len(df)}, columns: {len(df.columns)}")
    print(f"Modelling missing values: {sum(missing_counts[c] for c in MODEL_COLUMNS)}")
    print(f"Goal differences: positive={positive}, negative={negative}, zero={zero}")
    print(f"IQR flags: {len(outlier_rows)}; validation errors: {num_errors}; review-only observations: {num_review}")
    print("Checks:")
    for label, status, description in checks:
        print(f"  {status:6} {label}")
    print(f"Created {csv_path.name} and {report_path.name}")
    print(f"Input workbook unchanged (SHA-256: {input_hash_after})")


if __name__ == "__main__":
    main()
